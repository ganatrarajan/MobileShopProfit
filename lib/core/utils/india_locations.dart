  /// Returns sorted cities for a given state. If unknown or not matched, returns empty list.
  static List<String> getCitiesForState(String stateName) {
    final cleanState = stateName.trim();
    if (cleanState.isEmpty) return [];

    for (final entry in stateCities.entries) {
      if (entry.key.toLowerCase() == cleanState.toLowerCase() ||
          cleanState.toLowerCase().contains(entry.key.toLowerCase()) ||
          entry.key.toLowerCase().contains(cleanState.toLowerCase())) {
        final list = List<String>.from(entry.value);
        list.sort();
        return list;
      }
    }
    return [];
  }
